    /** 取文案；找不到 key 时原样返回 key，便于发现漏配。 */
    fun text(language: String, key: String): String {
        val table = if (language.startsWith("en")) enUS else zhCN
        return table[key] ?: zhCN[key] ?: key
    }

    /** 取文案并做 `{name}` 占位替换。 */
    fun format(language: String, key: String, args: Map<String, Any?>): String {
        var result = text(language, key)
        for ((name, value) in args) {
            result = result.replace("{$name}", value?.toString() ?: "")
        }
        return result
    }
